import psycopg

from app.models.note import Note
from app.repositories.notes import NotesRepository

class PostgresNotesRepository(NotesRepository):
    """Stores notes in PostgreSQL: SQL only, no business rules"""

    def __init__(self, connection: psycopg.Connection) -> None:
        """Take an open connection from outside(dependency injection)"""
        self._connection = connection

    def list_notes(self) -> list[Note]:
        """Read all notes from the table, newest first"""
        cursor = self._connection.cursor()
        try:
            cursor.execute("SELECT id, text, created_at FROM notes ORDER BY id DESC")
            rows = cursor.fetchall()
        finally:
            cursor.close()

        notes = []
        for row in rows:
            notes.append(self._row_to_note(row))
        return notes
    
    def get_note(self, note_id: int) -> Note | None:
        """Read one note by id; None if no row matches."""

        cursor = self._connection.cursor()
        try:
            cursor.execute(
                "SELECT id, text, created_at FROM notes WHERE id = %s", (note_id,),
            )
            row = cursor.fetchone()
        finally:
            cursor.close()

        if row is None:
            return None
        return self._row_to_note(row)

    
    def create_note(self, text: str) -> Note:
        """Insert a note and return it with the id and timestamp generated by database"""
        cursor = self._connection.cursor()
        try:
            cursor.execute(
                "INSERT INTO notes (text) VALUES (%s) RETURNING id, text, created_at", (text,),
            )
            row = cursor.fetchone()
            self._connection.commit()
        finally:
            cursor.close()

        return self._row_to_note(row)
    
    def update_note(self, note_id: int, text:str) -> Note | None:
        """Replace the text of a note; None of no note has this id"""
        cursor = self._connection.cursor()
        try:
            cursor.execute(
                "UPDATE notes SET text = %s WHERE id = %s RETURNING id, text, created_at", (text, note_id),
            )
            row = cursor.fetchone()
            self._connection.commit()
        finally:
            cursor.close()

        if row is None:
            return None
        return self._row_to_note(row)
    
    def delete_note(self, note_id: id) -> bool:
        """Delete note; return bool False if failed"""
        cursor = self._connection.cursor()
        try:
            cursor.execute("DELETE FROM notes WHERE id = %s", (note_id,))
            self._connection.commit()

            if cursor.rowcount == 1:
                return True
            return False
        finally:
            cursor.close()

    def _row_to_note(self, row: tuple) -> Note:
        """Turn one table row (id, text, created_at) into a domain model Note"""
        return Note(id=row[0], text=row[1], created_at=row[2])

        